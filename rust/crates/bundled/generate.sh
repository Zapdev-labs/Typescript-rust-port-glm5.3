#!/bin/sh
# Port of tsc/internal/bundled/generate.go @ ec47d33c23e464a17cdf2475632cba629bee8763
#
# Go's `//go:build ignore` generator becomes a shell script (same validation
# steps: lib entry naming, LF endings, copyright header, trailing newline),
# emitting libs_generated.rs + embed_generated.rs from tsc/internal/bundled/libs.
#
# Usage: sh generate.sh   (from rust/crates/bundled; paths resolve relative to
# this script's directory).

set -e
cd "$(dirname "$0")"

mkdir -p src

libs_dir="../../../tsc/internal/bundled/libs"
out_libs="src/libs_generated.rs"
out_embed="src/embed_generated.rs"

copyright_notice='../../../tsc/internal/bundled/CopyrightNotice.txt'

# readLibs: sorted list of lib.*.d.ts entries with the Go validations.
# LC_ALL=C: Go's sort.Strings is a byte sort; a locale-aware sort reorders
# punctuation (e.g. "lib.d.ts" vs "lib.decorators.d.ts").
libs=$(ls "$libs_dir" | LC_ALL=C sort)
[ -n "$libs" ] || { echo "no libs found in $libs_dir" >&2; exit 1; }

for name in $libs; do
    # Go: strings.HasPrefix(name, "lib.") && strings.HasSuffix(name, ".d.ts")
    case "$name" in
        lib.*)
            case "$name" in
                *.d.ts) ;;
                *) echo "unexpected entry in $libs_dir: $name" >&2; exit 1 ;;
            esac
            ;;
        *) echo "unexpected entry in $libs_dir: $name" >&2; exit 1 ;;
    esac
    if grep -q $'\r' "$libs_dir/$name"; then
        echo "$libs_dir/$name must use LF line endings" >&2
        exit 1
    fi
    if [ "$(tail -c1 "$libs_dir/$name" | wc -l)" -eq 0 ]; then
        echo "$libs_dir/$name must end with a newline" >&2
        exit 1
    fi
    # header check: copyright notice followed by a blank line
    header_len=$(wc -c < "$copyright_notice")
    head -c "$((header_len + 1))" "$libs_dir/$name" | cmp -s - <(cat "$copyright_notice"; echo) || {
        echo "$libs_dir/$name must start with CopyrightNotice.txt followed by a blank line" >&2
        exit 1
    }
done

# generateLibList
{
    echo '// Code generated by generate.sh (port of generate.go); DO NOT EDIT.'
    echo
    echo '/// LibNames is the list of all bundled lib files, sorted by name.'
    echo '/// For the list of libs sorted by load order, use `tsc_tsoptions::libs`.'
    echo 'pub static LIB_NAMES: &[&str] = &['
    for name in $libs; do
        echo "    \"$name\","
    done
    echo '];'
} > "$out_libs"

# generateEmbedded
{
    echo '// Code generated by generate.sh (port of generate.go); DO NOT EDIT.'
    echo
    echo '/// Go: `var embeddedContents map[string]string` — the embedded lib'
    echo '/// contents, keyed "libs/<name>", exactly like the Go map.'
    echo 'pub fn embedded_contents(key: &str) -> Option<&'"'"'static str> {'
    echo '    match key {'
    for name in $libs; do
        echo "        \"libs/$name\" => Some(include_str!(\"../../../../tsc/internal/bundled/libs/$name\")),"
    done
    echo '        _ => None,'
    echo '    }'
    echo '}'
} > "$out_embed"

echo "wrote $out_libs + $out_embed"
